"""Seeded synthetic daily sales. No real customer demand or outcomes."""
import csv
import json
import math
import random
from datetime import date, timedelta
from pathlib import Path

from dataio import SALES_COLUMNS, INVENTORY_COLUMNS

ROOT = Path(__file__).resolve().parent


def create(folder=None):
    folder = Path(folder or ROOT / 'data')
    folder.mkdir(parents=True, exist_ok=True)
    rng = random.Random(20261112)
    start, days = date(2024, 1, 1), 700
    sales = []
    for index in range(8):
        sku = f'SKU{index + 1:03d}'
        for t in range(days):
            day = start + timedelta(days=t)
            if index == 6:
                units = rng.randint(1, 6) if rng.random() < .17 else 0
            elif index == 7:
                units = 0
            else:
                level = 10 + index * 6
                trend = (0.018 if index in (0, 2, 4) else -.003) * t
                weekly = (5 + index) * math.sin(2 * math.pi * day.weekday() / 7)
                annual = (2 + index) * math.sin(2 * math.pi * t / 365.25)
                noise = rng.gauss(0, 1.8 + index * .25)
                # Demand shifts and rare bursts are not disclosed future features.
                shift = 7 if index == 3 and t >= 590 else 0
                burst = 12 if index == 5 and t % 43 == 0 else 0
                units = max(0, round(level + trend + weekly + annual + noise + shift + burst))
            sales.append({'date': day.isoformat(), 'sku': sku, 'units': units})
    stock = [25, 600, 140, 90, 850, 220, 4, 0]
    inventory = [{'sku': f'SKU{i + 1:03d}', 'as_of': (start + timedelta(days=days - 1)).isoformat(),
        'stock_on_hand': stock[i], 'on_order': 0 if i % 2 == 0 else 40,
        'lead_time_days': 7, 'review_period_days': 7, 'min_order_qty': 12, 'pack_size': 6,
        'unit_cost_vnd': 25_000 + 5_000 * i} for i in range(8)]
    for filename, rows, columns in [('sales.csv', sales, SALES_COLUMNS), ('inventory.csv', inventory, INVENTORY_COLUMNS)]:
        with (folder / filename).open('w', encoding='utf-8-sig', newline='') as out:
            writer = csv.DictWriter(out, fieldnames=columns)
            writer.writeheader()
            writer.writerows(rows)
    (folder / 'DATA_CARD.md').write_text(
        '# Synthetic demo data\n\n'
        'Seed: 20261112. Eight SKUs, 700 daily observations each (5,600 rows), generated by make_demo.py.\n'
        'Contains weekly/annual patterns, different trends, a late shift, occasional bursts, '
        'intermittent sales and an all-zero SKU. No real shop, customer, stockout or purchase outcome.\n'
        'Inventory is a hand-authored end-of-last-day snapshot. Dates are relative to this historical scenario.\n'
        'The creator knows the generator; chronological splits do not make this independent external validation.\n', encoding='utf-8')


if __name__ == '__main__':
    create()
    print('Created synthetic sales.csv and inventory.csv (8 SKUs × 700 days).')
